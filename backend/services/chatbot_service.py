# ============================================================
# DETECT CHAT TOPIC
# ============================================================

def detect_topic(message: str, language: str):

    text = message.lower()

    language_keywords = {}

    for topic, translations in KEYWORDS.items():

        words = translations.get(language, [])

        language_keywords[topic] = words

    for topic, words in language_keywords.items():

        for word in words:

            if word.lower() in text:
                return topic

    # Also check English as a fallback
    for topic, translations in KEYWORDS.items():

        for word in translations.get("en", []):

            if word.lower() in text:
                return topic

    return "general"


