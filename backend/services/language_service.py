# ============================================================
# GET ALL SUPPORTED LANGUAGES
# ============================================================

def get_supported_languages():

    return list(
        LANGUAGES.values()
    )


# ============================================================
# CHECK LANGUAGE
# ============================================================

def is_supported_language(
    language: str
):

    if not language:
        return False

    return (
        language.strip().lower()
        in LANGUAGES
    )


# ============================================================
# TRANSLATE MESSAGE
# ============================================================

def translate(
    key: str,
    language: str = "en"
):

    language = (
        language
        .strip()
        .lower()
    )

    # Fallback to English
    if language not in LANGUAGES:
        language = "en"

    message = TRANSLATIONS.get(
        key
    )

    # Unknown translation key
    if message is None:
        return key

    return message.get(
        language,
        message.get(
            "en",
            key
        )
    )


# ============================================================
# GET LANGUAGE INFORMATION
# ============================================================

def get_language_info(
    language: str
):

    language = (
        language
        .strip()
        .lower()
    )

    return LANGUAGES.get(
        language,
        LANGUAGES["en"]
    )


# ============================================================
# GET LANGUAGE NAME
# ============================================================

def get_language_name(
    language: str
):

    info = get_language_info(
        language
    )

    return info["name"]


# ============================================================
# GET NATIVE LANGUAGE NAME
# ============================================================

def get_native_language_name(
    language: str
):

    info = get_language_info(
        language
    )

    return info["native_name"]